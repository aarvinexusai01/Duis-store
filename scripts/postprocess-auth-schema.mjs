// Runs after `auth generate` (npm run auth:generate). Better Auth emits
// `timestamp` columns without a time zone; the project stores every instant
// as timestamptz (doc/02 §7) so processes in different time zones agree.
import { readFile, writeFile } from "node:fs/promises"

const FILE = "src/db/schema/auth.ts"

const source = await readFile(FILE, "utf8")
const updated = source.replace(
  /timestamp\("([a-z_]+)"\)/g,
  'timestamp("$1", { withTimezone: true })',
)

if (updated === source) {
  console.log(`${FILE}: no plain timestamp columns found`)
} else {
  await writeFile(
    FILE,
    `// Generated by \`npm run auth:generate\` (Better Auth CLI) — do not edit by hand.\n${updated}`,
  )
  console.log(`${FILE}: timestamp columns converted to timestamptz`)
}
