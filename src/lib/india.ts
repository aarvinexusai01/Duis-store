export function suggestStateForPincode(
  pincode: string,
): IndianStateCode | null {
  if (!/^[1-9][0-9]{5}$/.test(pincode)) return null
  return PREFIXES.find(([prefix]) => pincode.startsWith(prefix))?.[1] ?? null
}
